@CacheableTask
abstract class WriteTextFileTask : DefaultTask() {
    @get:Input
    abstract val content: Property<String>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun write() {
        outputFile.get().asFile.apply {
            parentFile.mkdirs()
            writeText(content.get())
        }
    }
}

@CacheableTask
abstract class CopyClasspathResourceTask : DefaultTask() {
    @get:Input
    abstract val resourceName: Property<String>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun copy() {
        val resource = resourceName.get()
        val contents = javaClass.classLoader.getResourceAsStream(resource)
            ?: throw IllegalStateException("Unable to find $resource in classpath")
        outputFile.get().asFile.apply {
            parentFile.mkdirs()
            writeBytes(contents.use { it.readBytes() })
        }
    }
}

internal fun Project.createJULLogForwarderClassTask() {
    val task =
        tasks.register("createJULForwarderClass", CreateJULForwarderClassTask::class.java) {
            group = "build"
            outputFile.set(generatedKotlinSourcesDir().resolve(project.kotlinPackageDir()).resolve("JULForwarder.kt"))
            packageName.set(project.kotlinPackage())
        }

    registerAutoGeneratedKotlinSourceTask(task)
}

@CacheableTask
abstract class CreateJULForwarderClassTask : DefaultTask() {
    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @get:Input
    abstract val packageName: Property<String>

    @TaskAction
    fun generate() {
        outputFile.get().asFile.apply {
            parentFile.mkdirs()
            writeText(
                """
                // $AUTO_GENERATED_CODE_WARNING
                package ${packageName.get()}

                import org.slf4j.bridge.SLF4JBridgeHandler
                import java.util.logging.LogManager

                object JULForwarder {
                    fun forward() {
                        LogManager.getLogManager().reset()
                        SLF4JBridgeHandler.removeHandlersForRootLogger()
                        SLF4JBridgeHandler.install()
                    }
                }
                """.trimIndent(),
            )
        }
}
}

private fun Project.getOrCreateAutoGenerateKotlinSourcesTask(): TaskProvider<out Task> {
    if (project.tasks.findByName("autoGenerateKotlinSources") != null) {
        return project.tasks.named("autoGenerateKotlinSources")
    }

    val sourcesDir = generatedKotlinSourcesDir()

    val autoGenerateKotlinSources =
            tasks.register("autoGenerateKotlinSources", SpecmaticAggregateTask::class.java) {
            group = "build"
            description = "Hook to auto-generate sources"
            outputs.dir(sourcesDir)
        }

    plugins.withType(JavaPlugin::class.java) {
        project.extensions.getByType(SourceSetContainer::class.java).named(SourceSet.MAIN_SOURCE_SET_NAME) {
            java {
                srcDir(autoGenerateKotlinSources.map { it.outputs })
            }
        }
    }

    tasks.withType(Delete::class.java) {
        delete(autoGenerateKotlinSources)
    }

    return autoGenerateKotlinSources
}

private fun Project.getOrCreateAutoGenerateResourcesTask(): TaskProvider<out Task> {
    if (project.tasks.findByName("autoGenerateResources") != null) {
        return project.tasks.named("autoGenerateResources")
    }

    val resourcesDir = generatedResourcesDir()

    val autoGenerateResources =
            tasks.register("autoGenerateResources", SpecmaticAggregateTask::class.java) {
            group = "build"
            description = "Hook to auto-generate resources"
            outputs.dir(resourcesDir)
        }

    plugins.withType(JavaPlugin::class.java) {
        project.extensions.getByType(SourceSetContainer::class.java).named(SourceSet.MAIN_SOURCE_SET_NAME) {
            resources {
                srcDir(autoGenerateResources.map { it.outputs })
            }
        }
    }

    tasks.withType(Delete::class.java) {
        delete(resourcesDir)
    }

    return autoGenerateResources
}
