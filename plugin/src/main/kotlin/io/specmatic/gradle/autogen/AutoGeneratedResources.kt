internal fun Project.generatedResourcesDir(): File = file("src/main/gen-resources")

internal fun Project.generatedKotlinSourcesDir(): File = file("src/main/gen-kt")

internal fun Project.registerAutoGeneratedKotlinSourceTask(vararg tasks: Any?) {
    project.getOrCreateAutoGenerateKotlinSourcesTask().configure {
        dependsOn(tasks)
    }
}

internal fun Project.registerAutoGeneratedResourcesTask(vararg tasks: Any?) {
    project.getOrCreateAutoGenerateResourcesTask().configure {
        dependsOn(tasks)
    }
}

internal fun Project.createEditorConfigFile(): TaskProvider<CopyClasspathResourceTask> {
    val task =
        tasks.register("createEditorConfigFile", CopyClasspathResourceTask::class.java) {
            group = "build"
            resourceName.set("editorconfig")
            outputFile.set(rootProject.file(".editorconfig"))
        }

    registerAutoGeneratedResourcesTask(task)

    return task
}

internal fun Project.createVersionPropertiesFileTask(versionInfoForProject: ProjectVersionInfo) {
    val task =
        tasks.register("createVersionPropertiesFile", WriteTextFileTask::class.java) {
            group = "build"
            content.set(versionInfoForProject.toPropertiesFile())
            outputFile.set(generatedResourcesDir().resolve(versionInfoForProject.propertiesFilePath()))
        }

    registerAutoGeneratedResourcesTask(task)
}

internal fun Project.createVersionInfoKotlinTask(versionInfoForProject: ProjectVersionInfo) {
    val task =
        tasks.register("createVersionInfoKotlin", WriteTextFileTask::class.java) {
            group = "build"
            content.set(versionInfoForProject.toKotlinClass())
            outputFile.set(generatedKotlinSourcesDir().resolve(versionInfoForProject.kotlinFilePath()))
        }

    registerAutoGeneratedKotlinSourceTask(task)
}

